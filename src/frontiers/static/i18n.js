  const preference = "frontiers.language";
  let language = "ru";
  try { if (localStorage.getItem(preference) === "en") language = "en"; } catch {}

  function t(message, ...args) {
    const template = language === "en" && Object.hasOwn(english, message) ? english[message] : message;
    return args.length ? template.replace(/\{(\d+)\}/g, (slot, index) => args[index] ?? slot) : template;
  }

  function errorText(message) {
    if (language !== "en") return message;
    const unavailable = /^Карта «(.+)» недоступна выбранной фракции\.$/.exec(message);
    if (unavailable) return t("Карта «{0}» недоступна выбранной фракции.", t(unavailable[1]));
    const copies = /^Слишком много копий карты «(.+)»\.$/.exec(message);
    if (copies) return t("Слишком много копий карты «{0}».", t(copies[1]));
    return t(message);
  }

  // Capture only original markup, before the game renders player or deck names.
  const staticText = [];
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const source = node.textContent.trim();
    if (Object.hasOwn(english, source)) staticText.push({node, source, original: node.textContent});
  }
  const attributes = [];
  for (const element of document.querySelectorAll("[aria-label], [title], [placeholder]")) {
    for (const name of ["aria-label", "title", "placeholder"]) {
      const source = element.getAttribute(name);
      if (source && Object.hasOwn(english, source)) attributes.push({element, name, source});
    }
  }

  function apply() {
    document.documentElement.lang = language;
    for (const {node, source, original} of staticText) {
      if (node.isConnected) node.textContent = original.replace(source, t(source));
    }
    for (const {element, name, source} of attributes) {
      if (element.isConnected) element.setAttribute(name, t(source));
    }
    const button = document.getElementById("language-button");
    button.textContent = language === "ru" ? "EN" : "RU";
    const label = language === "ru" ? "Switch to English" : "Переключить на русский";
    button.setAttribute("aria-label", label);
    button.title = label;
  }

  function toggle() {
    language = language === "ru" ? "en" : "ru";
    try { localStorage.setItem(preference, language); } catch {}
    apply();
  }

  function catalog(source) {
    if (typeof source === "string") return t(source);
    if (Array.isArray(source)) return source.map(catalog);
    if (source && typeof source === "object") {
      return Object.fromEntries(Object.entries(source).map(([key, value]) => [key, catalog(value)]));
    }
    return source;
  }

  apply();
  return {t, errorText, toggle, catalog, get language() { return language; }};
